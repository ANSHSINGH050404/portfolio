function formatDate(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return "";
  return d.toLocaleDateString("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
  });
}

function PRBadge({ state }: { state: PRCard["state"] }) {
  const label =
    state === "open" ? "Open" : state === "merged" ? "Merged" : "Closed";
  const color = state === "open" ? "#28c840" : state === "merged" ? "#a78bfa" : "#6e6e73";
  return (
    <span
      style={{
        display: "inline-flex",
        alignItems: "center",
        gap: 6,
        fontFamily: "var(--font-mono)",
        fontSize: 10,
        letterSpacing: "0.1em",
        textTransform: "uppercase",
        color: state === "open" ? "#28c840" : "var(--muted)",
      }}
    >
      <span
        aria-hidden
        style={{
          width: 7,
          height: 7,
          borderRadius: "50%",
          background: color,
          boxShadow: state === "open" ? "0 0 8px #28c84080" : "none",
          flexShrink: 0,
        }}
      />
      {label}
    </span>
  );
}

function PRMarqueeCard({ pr }: { pr: PRCard }) {
  return (
    <a
      href={pr.url}
      target="_blank"
      rel="noreferrer"
      data-hover
      className="pr-card"
      aria-label={`${pr.repo} pull request ${pr.number}: ${pr.title}`}
    >
      <div className="pr-card-top">
        <span className="pr-card-repo">{pr.repo}</span>
        <span className="pr-card-num">#{pr.number}</span>
      </div>
      <div className="pr-card-title">{pr.title}</div>
      <div className="pr-card-foot">
        <PRBadge state={pr.state} />
        <span className="pr-card-date">{formatDate(pr.updatedAt)}</span>
      </div>
    </a>
  );
}

function MarqueeRow({
  prs,
  reverse,
  label,
}: {
  prs: PRCard[];
  reverse?: boolean;
  label: string;
}) {
  const doubled = [...prs, ...prs];
  return (
    <div className="pr-marquee" role="list" aria-label={label}>
      <div className={`pr-track${reverse ? " reverse" : ""}`}>
        {doubled.map((pr, i) => (
          <div
            key={`${pr.id}-${i}`}
            role="listitem"
            aria-hidden={i >= prs.length}
            // The doubled copy is visual-only for the seamless loop; without
            // this its links stay in the tab order behind an aria-hidden node.
            inert={i >= prs.length}
            style={{ flexShrink: 0 }}
          >
            <PRMarqueeCard pr={pr} />
          </div>
        ))}
      </div>
    </div>
  );
}

export function PRWall() {
  const [ref, visible] = useReveal<HTMLDivElement>(0.08);
  const [prs, setPrs] = useState<PRCard[]>(FALLBACK_PRS);
  const [total, setTotal] = useState<number | null>(null);
  const [mergedTotal, setMergedTotal] = useState<number | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        // Same cached aggregation GitHubStreak uses — no direct api.github.com
        // call from the browser, so one visitor can't exhaust the rate limit.
        const res = await fetch("/api/github");
        if (!res.ok) throw new Error(`api ${res.status}`);
        const data = (await res.json()) as {
          ok?: boolean;
          prs?: PRCard[];
          prTotal?: number;
          prMergedTotal?: number;
        };
        if (cancelled) return;
        if (data.ok === false || !Array.isArray(data.prs)) {
          throw new Error("unavailable");
        }
        if (data.prs.length > 0) setPrs(data.prs);
        if (typeof data.prTotal === "number") setTotal(data.prTotal);
        if (typeof data.prMergedTotal === "number") {
          setMergedTotal(data.prMergedTotal);
        }
      } catch {
        // Keep fallback PRs — section still renders offline / rate-limited.
      } finally {
        if (!cancelled) setLoading(false);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  const [rowA, rowB] = useMemo(() => {
    const mid = Math.max(1, Math.ceil(prs.length / 2));
    return [prs.slice(0, mid), prs.slice(mid)];
  }, [prs]);

  return (
    <section id="prs" className="section-pad" aria-label="Pull requests">
      <div className="section-line" />
      <div ref={ref}>
        <div className={`fi ${visible ? "in" : ""}`} style={{ marginBottom: 40 }}>
          <div className="section-label">Open source</div>
          <div
            style={{
              display: "flex",
              justifyContent: "space-between",
              alignItems: "flex-end",
              flexWrap: "wrap",
              gap: 20,
            }}
          >
            <h2 className="section-title">
              Pull requests
              <br />
              <span className="outline">shipped upstream</span>
            </h2>
            <div
              style={{
                display: "flex",
                alignItems: "center",
                gap: 12,
                flexWrap: "wrap",
              }}
            >
              <span
                style={{
                  fontFamily: "var(--font-mono)",
                  fontSize: 11,
                  color: "var(--muted)",
                  letterSpacing: "0.08em",
                }}
              >
                {loading
                  ? "loading…"
                  : `${total ?? prs.length} upstream · ${mergedTotal ?? 0} merged`}
              </span>
              <a
                href={`https://github.com/pulls?q=author:${GITHUB_USER}+-user:${GITHUB_USER}`}
                target="_blank"
                rel="noreferrer"
                className="btn-ghost"
                style={{ padding: "8px 16px", fontSize: 13 }}
              >
                View all ↗
              </a>
            </div>
          </div>
          <p
            style={{
              maxWidth: 560,
              color: "var(--muted)",
              fontSize: 16,
              lineHeight: 1.55,
              marginTop: 16,
            }}
          >
            Pull requests opened against repositories I don&apos;t own — the
            purple ones were merged, grey ones were closed unmerged. Hover to
            pause, click any card to review the PR on GitHub.
          </p>
        </div>

        <div
          className={`fi ${visible ? "in" : ""}`}
          style={{
            transitionDelay: "0.12s",
            display: "flex",
            flexDirection: "column",
            gap: 12,
            marginLeft: "calc(clamp(22px, 5vw, 80px) * -1)",
            marginRight: "calc(clamp(22px, 5vw, 80px) * -1)",
          }}
        >
          <MarqueeRow prs={rowA} label="Recently updated pull requests, row one" />
          {rowB.length > 0 && (
            <MarqueeRow prs={rowB} reverse label="Recently updated pull requests, row two" />
          )}
        </div>
      </div>
    </section>
  );
}
