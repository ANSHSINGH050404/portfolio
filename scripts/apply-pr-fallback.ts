import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

/**
 * Rewrites the FALLBACK_PRS constant in components/PRWall.tsx using freshly
 * generated data from the GitHub API.
 */
const target = "components/PRWall.tsx";
const source = readFileSync(target, "utf8");

const generated = execSync("bun scripts/gen-pr-fallback.ts", {
	encoding: "utf8",
	maxBuffer: 1024 * 1024,
});

const start = source.indexOf("const FALLBACK_PRS: PRCard[] = [");
if (start === -1) {
	console.error("Could not find the FALLBACK_PRS block.");
	process.exit(1);
}
const marker = "];";
const end = source.indexOf(marker, start);
if (end === -1) {
	console.error("Could not find the end of the FALLBACK_PRS block.");
	process.exit(1);
}

const block = `/**
 * Last-resort fallback used only when the GitHub API is unreachable or
 * rate-limited. Generated by \`bun scripts/gen-pr-fallback.ts\` so the states
 * and titles match reality instead of drifting from a hand-maintained copy.
 */
${generated.trim()}`;

writeFileSync(target, source.slice(0, start) + block + source.slice(end + marker.length));
console.log("FALLBACK_PRS regenerated.");
