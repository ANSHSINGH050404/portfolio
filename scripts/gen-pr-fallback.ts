/**
 * Regenerates the PR-wall fallback list from the live GitHub API so the
 * offline fallback shows real, currently-accurate pull requests instead of a
 * hand-maintained copy that drifts.
 *
 * Run with `bun scripts/gen-pr-fallback.ts`.
 */
const API = "https://api.github.com";
const GITHUB_USER = "ANSHSINGH050404";

const headers: Record<string, string> = {
	Accept: "application/vnd.github+json",
	"User-Agent": `${GITHUB_USER}-portfolio`,
	...(process.env.GITHUB_TOKEN
		? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` }
		: {}),
};

export {};

async function gh<T>(url: string): Promise<T> {
	const res = await fetch(url, { headers });
	if (!res.ok) throw new Error(`GitHub ${res.status}`);
	return (await res.json()) as T;
}

type SearchItem = {
	number: number;
	title: string;
	state: string;
	html_url: string;
	repository_url: string;
	updated_at: string;
	pull_request?: { merged_at?: string | null } | null;
};

const page = await gh<{ items: SearchItem[] }>(
	`${API}/search/issues?q=author:${GITHUB_USER}+type:pr+-user:${GITHUB_USER}&per_page=50&sort=updated&order=desc`,
);

// Prefer merged work; fall back to open PRs so the wall still shows activity.
const merged = page.items.filter((i) => i.pull_request?.merged_at);
const open = page.items.filter((i) => i.state === "open");
const picked = [...merged, ...open].slice(0, 10);

const rows = picked.map((item) => {
	const repo = item.repository_url.replace(`${API}/repos/`, "");
	const state = item.state === "open" ? "open" : item.pull_request?.merged_at ? "merged" : "closed";
	const id = `${repo.toLowerCase()}#${item.number}`;
	return {
		id,
		repo,
		number: item.number,
		title: item.title,
		state,
		url: item.html_url,
		updatedAt: item.updated_at,
	};
});

console.log(`// Generated by scripts/gen-pr-fallback.ts on ${new Date().toISOString().slice(0, 10)}`);
console.log("const FALLBACK_PRS: PRCard[] = [");
for (const row of rows) {
	console.log("  {");
	console.log(`    id: ${JSON.stringify(row.id)},`);
	console.log(`    repo: ${JSON.stringify(row.repo)},`);
	console.log(`    number: ${row.number},`);
	console.log(`    title: ${JSON.stringify(row.title)},`);
	console.log(`    state: ${JSON.stringify(row.state)},`);
	console.log(`    url: ${JSON.stringify(row.url)},`);
	console.log(`    updatedAt: ${JSON.stringify(row.updatedAt)},`);
	console.log("  },");
}
console.log("];");
